const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {createApp}=require('../server.js');
const {ProjectScope}=require('../src/project-scope.js');
test('雙層授權：全域搜尋、專案寫入、排除、撤銷與重啟',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'cda-global-'));
  let server,instance;
  t.after(async()=>{if(server)await new Promise(r=>server.close(r));if(instance)await instance.saved.queue;await fs.rm(base,{recursive:true,force:true});});
  const tree=path.join(base,'ReAct'),a=path.join(tree,'a'),b=path.join(tree,'b');
  for(const dir of [a,b,path.join(a,'demo'),...['node_modules','.git','runtime','backups','code_and_document_assistant'].map(n=>path.join(tree,n))])await fs.mkdir(dir,{recursive:true});
  for(const name of ['a/index.js','b/index.js','a/demo/sample.md','node_modules/hide.js','.git/hide.js','runtime/hide.js','backups/hide.js','code_and_document_assistant/hide.js','.env.local'])await fs.writeFile(path.join(tree,name),'const marker = 1;');
  instance=await createApp({runtime:path.join(base,'state'),adminToken:'abcdef'});
  server=instance.app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const url='http://127.0.0.1:'+server.address().port,session=await fetch(url+'/api/session');
  const headers={cookie:session.headers.get('set-cookie').split(';')[0],'x-cda-token':(await session.json()).csrf,'content-type':'application/json'};
  const request=async(endpoint,body,project='demo')=>{const r=await fetch(url+endpoint,{method:body===undefined?'GET':'POST',headers:{...headers,'x-cda-project':project},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,body:await r.json()};};
  const grant=async(folder,kind,write=false)=>{const q=await request('/api/roots/request',{path:folder,kind,write});assert.equal(q.status,200);const result=await request('/api/roots/'+q.body.id+'/approve',{adminToken:'abcdef'});assert.equal(result.status,200,JSON.stringify(result.body));return result.body.root;};
  assert.equal((await request('/api/roots/request',{path:tree,kind:'global-reference',write:true})).status,400);
  const global=await grant(tree,'global-reference'),target=await grant(a,'project',true);
  const catalog=(await request('/api/catalog')).body;
  assert.equal(catalog.projects.some(r=>r.id===global.id),false);
  assert.equal(catalog.globalReferences[0].kind,'global-reference');
  const inventory=(await request('/api/files',undefined,target.id)).body;
  assert.equal(inventory.files.length,3);
  assert.equal(new Set(inventory.files.map(f=>f.path)).size,3,'同一路徑去重');
  const local=inventory.files.find(f=>f.path===path.join(a,'index.js')),foreign=inventory.files.find(f=>f.path===path.join(b,'index.js'));
  assert.equal(local.writable,true);assert.equal(foreign.writable,false);
  assert.ok(inventory.files.some(f=>f.path===path.join(a,'demo/sample.md')));
  assert.equal((await request('/api/files',undefined,global.id)).status,400);
  assert.equal((await request('/api/proposals',{fileId:foreign.id,version:foreign.hash,after:'const changed=2;',adminToken:'abcdef'},target.id)).status,400);
  assert.equal((await request('/api/files/'+foreign.id+'/verify',{adminToken:'abcdef'},target.id)).status,400);
  const scope=new ProjectScope(instance.workspace,target.id);
  assert.ok((await scope.search('marker')).some(e=>e.path===foreign.path));
  const proposal=await scope.createProposal(local.id,'const changed=2;');await scope.apply(proposal);
  assert.equal(await fs.readFile(foreign.path,'utf8'),'const marker = 1;');
  await fs.writeFile(path.join(b,'new.txt'),'marker addition');await request('/api/index',{},target.id);
  assert.ok((await request('/api/files',undefined,target.id)).body.files.some(f=>f.name==='b'+path.sep+'new.txt'));
  await fs.unlink(path.join(b,'new.txt'));await request('/api/index',{},target.id);
  assert.equal((await request('/api/files',undefined,target.id)).body.files.some(f=>f.name.endsWith('new.txt')),false);
  await request('/api/roots/'+global.id+'/revoke',{adminToken:'abcdef'});
  assert.equal((await request('/api/files/'+foreign.id,undefined,target.id)).status,400);
  assert.equal((await request('/api/files',undefined,target.id)).body.files.length,2);
  await assert.rejects(scope.read(foreign.id));
  await new Promise(r=>server.close(r));server=null;await instance.saved.queue;
  instance=await createApp({runtime:path.join(base,'state')});
  const restored=instance.workspace.roots.find(r=>r.id===global.id);
  assert.equal(restored.kind,'global-reference');assert.equal(instance.workspace.active(restored),false);
  assert.equal(instance.workspace.files.some(f=>f.rootId===global.id),false);
});
