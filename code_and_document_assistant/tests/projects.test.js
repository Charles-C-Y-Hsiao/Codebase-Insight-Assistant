const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {createApp}=require('../server.js');

test('專案建立：授權、預覽不寫入、確認、取消、版本與路徑界線',async t=>{
  const base=require('node:os').tmpdir();
  const temp=await fs.mkdtemp(path.join(base,'project-test-'));
  t.after(async()=>{if(path.dirname(temp)===base&&path.basename(temp).startsWith('project-test-'))await fs.rm(temp,{recursive:true,force:true});});
  const {app,workspace,projects,adminToken}=await createApp({runtime:path.join(temp,'state')});
  assert.match(adminToken,/^[0-9a-f]{6}$/,'自動管理碼應為 6 碼十六進位字串');
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  t.after(()=>new Promise(r=>server.close(r)));
  const url='http://127.0.0.1:'+server.address().port;
  const session=await fetch(url+'/api/session'),cookie=session.headers.get('set-cookie').split(';')[0],{csrf}=await session.json();
  let targetProject='demo';
  const post=async(endpoint,body)=>{const r=await fetch(url+endpoint,{method:'POST',headers:{Cookie:cookie,'X-CDA-Token':csrf,'X-CDA-Project':targetProject,'Content-Type':'application/json'},body:JSON.stringify(body)});return {status:r.status,body:await r.json()};};
  const creationParent=path.join(temp,'creation-parent'),createdPath=path.join(creationParent,'collapsible-tool');await fs.mkdir(creationParent);
  const createRequest=(await post('/api/roots/request',{path:createdPath,create:true,write:true,verify:true})).body;
  await assert.rejects(fs.access(createdPath),'提出請求時不可建立資料夾');
  const created=(await post('/api/roots/'+createRequest.id+'/approve',{adminToken})).body;
  assert.equal(created.created,true);assert.equal(created.root.path,await fs.realpath(createdPath));assert.ok((await fs.stat(createdPath)).isDirectory());
  const existingPath=path.join(creationParent,'already-there');await fs.mkdir(existingPath);await fs.writeFile(path.join(existingPath,'keep.txt'),'keep');
  const existingRequest=(await post('/api/roots/request',{path:existingPath,create:true})).body;
  assert.equal((await post('/api/roots/'+existingRequest.id+'/approve',{adminToken})).status,400);
  assert.equal(await fs.readFile(path.join(existingPath,'keep.txt'),'utf8'),'keep','建立模式不可覆寫既有資料夾');
  const parent=path.join(temp,'new-projects');await fs.mkdir(parent);
  const request=(await post('/api/roots/request',{path:parent,write:true,verify:true})).body;
  assert.ok(!workspace.roots.some(r=>r.path===parent));
  assert.equal((await post('/api/roots/'+request.id+'/approve',{})).status,403);
  const root=(await post('/api/roots/'+request.id+'/approve',{adminToken})).body.root;
  targetProject=root.id;
  const args={rootId:root.id,name:'product_picker',template:'select2-products',adminToken};
  assert.equal((await post('/api/projects',{...args,adminToken:'wrong'})).status,403);
  for(const name of ['../escape','C:\\outside','nested/path','CON','name.html',''])assert.equal((await post('/api/projects',{...args,name})).status,400);
  assert.equal((await post('/api/projects',{...args,template:'shell'})).status,400);
  const p=(await post('/api/projects',args)).body;assert.equal(p.status,'awaiting_approval');
  await assert.rejects(fs.access(p.path));
  assert.throws(()=>projects.get(p.id,'another-session'),/工作階段/);
  const done=(await post('/api/projects/'+p.id+'/apply',{adminToken})).body;
  assert.equal(done.status,'completed');assert.equal(done.result.verification.status,'passed');
  assert.equal(done.result.indexed.length,1);assert.equal(await fs.readFile(path.join(p.path,'index.html'),'utf8'),p.files[0].after);
  const preview=await fetch(url+done.result.previewUrl,{headers:{Cookie:cookie}});
  assert.equal(preview.status,200);assert.match(preview.headers.get('content-security-policy'),/sandbox allow-scripts;/);
  assert.equal((await fetch(url+done.result.previewUrl)).status,403);
  assert.equal((await post('/api/projects',args)).status,400);
  assert.equal((await post('/api/projects/'+p.id+'/apply',{adminToken})).status,400);
  await fs.appendFile(path.join(p.path,'index.html'),'<!-- external edit -->');
  assert.equal((await fetch(url+done.result.previewUrl,{headers:{Cookie:cookie}})).status,400);
  const cancelled=(await post('/api/projects',{...args,name:'cancelled'})).body;
  await post('/api/projects/'+cancelled.id+'/cancel',{adminToken});
  assert.equal((await post('/api/projects/'+cancelled.id+'/apply',{adminToken})).status,400);
  await assert.rejects(fs.access(cancelled.path));
  const conflict=(await post('/api/projects',{...args,name:'conflict'})).body;
  await fs.mkdir(conflict.path);await fs.writeFile(path.join(conflict.path,'keep.txt'),'keep');
  assert.equal((await post('/api/projects/'+conflict.id+'/apply',{adminToken})).status,400);
  assert.equal(await fs.readFile(path.join(conflict.path,'keep.txt'),'utf8'),'keep');
  const expired=(await post('/api/projects',{...args,name:'expired'})).body;
  await workspace.revoke(root.id);
  assert.equal((await post('/api/projects/'+expired.id+'/apply',{adminToken})).status,400);
  await assert.rejects(fs.access(expired.path));
  const ro=await workspace.authorize(parent);
  assert.equal((await post('/api/projects',{...args,rootId:ro.id,name:'readonly'})).status,400);
});
